#!/usr/bin/env python3
"""vol16b build step: whitespace-free copies of Coach's start-up data files into data/min/ (the app fetches these first).
Never edits Coach's files. Each copy must parse to exactly the same value as its source, else the script stops (exit 1).
data/min/manifest.json records source md5, min md5 and sizes. Run after every Coach data sync: python3 tools/min-data.py"""
import json, hashlib, os, sys
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data')
FILES = ['exercises.json', 'rules.json', 'targets.json', 'patterns.json', 'splits.json', 'volume-model.json',
         'splits-efficient-diff.json', 'splits-efficient.json', 'fatigue.json', 'custom-exercise-defaults.json', 'templates.json']
md5 = lambda b: hashlib.md5(b).hexdigest()
os.makedirs(os.path.join(D, 'min'), exist_ok=True)
man = {'note': 'generated by tools/min-data.py from the files beside it; same content, no whitespace. Do not edit.', 'files': {}}
for f in FILES:
    src = open(os.path.join(D, f), 'rb').read(); v = json.loads(src)
    out = json.dumps(v, separators=(',', ':'), ensure_ascii=False).encode('utf-8')
    if json.loads(out) != v: sys.exit(f'STOP: {f} min copy does not round-trip')
    open(os.path.join(D, 'min', f), 'wb').write(out)
    man['files'][f] = {'src_md5': md5(src), 'min_md5': md5(out), 'src_bytes': len(src), 'min_bytes': len(out)}
    print(f'{f:32s} {len(src):>8d} -> {len(out):>8d}  src {md5(src)}')
open(os.path.join(D, 'min', 'manifest.json'), 'w').write(json.dumps(man, indent=1))
